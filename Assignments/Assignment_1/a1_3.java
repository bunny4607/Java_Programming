class Display{
    //////////////////////////////////////////////////////////////
    //
    //  Function Name   : display
    //  Description     : Prints numbers from 5 to 1
    //  Input           : None
    //  Output          : void
    //
    //////////////////////////////////////////////////////////////
    public void display(){


        int iNo = 0 ; 
        for (iNo =5 ; iNo >= 1; iNo--){
            System.out.println(iNo);
        }
    }
}

//////////////////////////////////////////////////////////////////
//
//                      Entry Point
//
//////////////////////////////////////////////////////////////////

public class a1_3 {
    public static void main(String A[]){

        Display dobj = new Display(); 

        dobj.display();
    }
}

